"""Run the large-road route choice (D34) at many times of day and keep what the cameras saw.

Each tick runs the real decision for a few fixed trips, saves every camera frame it read under
data/raw/camera_samples/<date>/<HHMM>/ and appends one line per trip to decisions.jsonl, so the
model's labels can be checked against the photos and the choice can be compared across the day.

    python3 pipelines/camera_sampler.py --once
    python3 pipelines/camera_sampler.py --until 19:30          # every 15 min during 07:00–09:00 and 16:00–19:30
    python3 pipelines/camera_sampler.py --report               # → docs/eval/camera-sampler.md
"""
from __future__ import annotations

import argparse
import collections
import json
import sys
import time
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from app import cameras, corridor  # noqa: E402

OUT = ROOT / "data" / "raw" / "camera_samples"
REPORT = ROOT / "docs" / "eval" / "camera-sampler.md"
TRIPS = [
    ("Quận 1 → Vạn Phúc City", (10.7798, 106.6990), (10.8455, 106.7185)),
    ("Vạn Phúc City → Quận 1", (10.8455, 106.7185), (10.7798, 106.6990)),
    ("Quận 1 → Thảo Điền (qua Cầu Sài Gòn?)", (10.7798, 106.6990), (10.8030, 106.7380)),
]
PEAKS = ((7, 0, 9, 0), (16, 0, 19, 30))


def tick() -> None:
    now = datetime.now(corridor.VN_TZ)
    folder = OUT / now.strftime("%Y-%m-%d") / now.strftime("%H%M")
    folder.mkdir(parents=True, exist_ok=True)
    for name, o, d in TRIPS:
        try:
            res = corridor.corridor(o, d, "toyota-vios")
        except Exception as exc:  # keep sampling through a bad tick
            print(f"{now:%H:%M} {name}: {type(exc).__name__}")
            continue
        for r in res.get("routes", []):
            for h in r["hotspots"]:
                for c in h["cameras"]:
                    img = cameras._snaps.get(c["id"], (0, None))[1]
                    if img and not (folder / f"{c['id']}.jpg").exists():
                        (folder / f"{c['id']}.jpg").write_bytes(img)
        line = {"at": now.isoformat(timespec="minutes"), "trip": name, "summary": res.get("summary"),
                "typical_factor": res.get("typical_factor"), "read": res.get("cameras_read"),
                "offline": res.get("cameras_offline"),
                "routes": [{"label": r["label"], "chosen": r["chosen"], "base_min": r["base_min"], "eta_min": r["eta_min"],
                            "status": r["status"], "hotspots": [{"name": h["name"], "traffic": h["traffic"],
                                                                 "depth_cm": h["depth_cm"]} for h in r["hotspots"]]}
                           for r in res.get("routes", [])]}
        with open(OUT / "decisions.jsonl", "a", encoding="utf-8") as f:
            f.write(json.dumps(line, ensure_ascii=False) + "\n")
        best = next((r for r in line["routes"] if r["chosen"]), None)
        print(f"{now:%H:%M} {name}: {best and best['label']} {best and best['eta_min']} min "
              f"(×{line['typical_factor']}, {line['read']} read, {line['offline']} offline)", flush=True)
    with open(folder / "readings.json", "w", encoding="utf-8") as f:
        json.dump({k: cameras.public(v) for k, v in cameras._reads.items()}, f, ensure_ascii=False)


def in_peak(t: datetime) -> bool:
    m = t.hour * 60 + t.minute
    return any(a * 60 + b <= m <= c * 60 + d for a, b, c, d in PEAKS)


def report() -> None:
    rows = [json.loads(x) for x in (OUT / "decisions.jsonl").read_text(encoding="utf-8").splitlines() if x.strip()]
    lines = ["# Camera route choice across the day", "",
             "Generated by `pipelines/camera_sampler.py --report` from `data/raw/camera_samples/decisions.jsonl`.", ""]
    for name, _, _ in TRIPS:
        mine = [r for r in rows if r["trip"] == name]
        if not mine:
            continue
        lines += [f"## {name}", "", "| Time | Chosen route | ETA | Goong-only ETA | Typical × | Jams seen | Read / offline |",
                  "|---|---|---|---|---|---|---|"]
        for r in mine:
            best = next((x for x in r["routes"] if x["chosen"]), {})
            jams = sorted({h["name"] for x in r["routes"] for h in x["hotspots"] if h["traffic"] in ("un_u", "ket_cung")})
            goong = r["routes"][0] if r["routes"] else {}
            lines.append(f"| {r['at'][11:16]} | {best.get('label', '')} | {best.get('eta_min', '')} | "
                         f"{goong.get('eta_min', '')} | {r['typical_factor']} | {', '.join(jams) or '–'} | "
                         f"{r['read']} / {r['offline']} |")
        lines.append("")
    levels = collections.Counter(h["traffic"] for r in rows for x in r["routes"] for h in x["hotspots"])
    lines += ["## Traffic levels over all readings", "", ", ".join(f"{k}: {v}" for k, v in levels.most_common()), ""]
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"→ {REPORT}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--once", action="store_true")
    ap.add_argument("--until", help="HH:MM (next occurrence, Vietnam time)")
    ap.add_argument("--report", action="store_true")
    a = ap.parse_args()
    if a.report:
        return report()
    if a.once or not a.until:
        return tick()
    h, m = map(int, a.until.split(":"))
    end = datetime.now(corridor.VN_TZ).replace(hour=h, minute=m, second=0, microsecond=0)
    if end <= datetime.now(corridor.VN_TZ):
        end += timedelta(days=1)
    while datetime.now(corridor.VN_TZ) < end:  # rush hours only, to spare the free model quota
        start = time.time()
        if in_peak(datetime.now(corridor.VN_TZ)):
            tick()
        time.sleep(max(60, 900 - (time.time() - start)))

if __name__ == "__main__":
    main()
